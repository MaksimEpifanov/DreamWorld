import 'package:flutter/material.dart';

class FishingTypeInfo {
  const FishingTypeInfo({
    required this.title,
    required this.category,
    required this.icon,
    required this.short,
    required this.description,
    required this.gear,
    required this.baits,
    required this.place,
    required this.tip,
  });

  final String title;
  final String category;
  final IconData icon;
  final String short;
  final String description;
  final List<String> gear;
  final List<String> baits;
  final String place;
  final String tip;
}

class FishingTip {
  const FishingTip({required this.title, required this.body, required this.icon});

  final String title;
  final String body;
  final IconData icon;
}

class FishingMistake {
  const FishingMistake({
    required this.title,
    required this.body,
    required this.fix,
    required this.icon,
  });

  final String title;
  final String body;
  final String fix;
  final IconData icon;
}

class FishingSafetyRule {
  const FishingSafetyRule({
    required this.title,
    required this.body,
    required this.icon,
  });

  final String title;
  final String body;
  final IconData icon;
}

class FishingSource {
  const FishingSource({required this.title, required this.url});

  final String title;
  final String url;
}

