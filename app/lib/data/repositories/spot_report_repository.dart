/// Счётчик жалоб на авторов заметок карты.
///
/// Хранится отдельно от самих жалоб: для каждой жалобы достаточно знать, сколько
/// разных пользователей пожаловались на автора. Если жалоб больше 3, его заметки
/// убираются у всех. В рабочей версии счётчик общий (Firestore), в мок-режиме —
/// в памяти.
abstract interface class SpotReportRepository {
  /// Регистрирует жалобу текущего пользователя на автора заметок.
  ///
  /// Повторная жалоба того же пользователя не увеличивает счётчик. Возвращает
  /// общее число пользователей, пожаловавшихся на [authorId].
  Future<int> registerReport({
    required String authorId,
    required String authorName,
  });
}
